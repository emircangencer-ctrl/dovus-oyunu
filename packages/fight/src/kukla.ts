/** Taban pikselini sabit noktaya çevirir; kesirler 1/256'nın katı olmalı (veri tablosu için, yükleme anında). */
const px = (n: number): number => {
  const v = n * FX;
  if (!Number.isInteger(v)) throw new Error(`${n} piksel 1/256'nın katı değil`);
  return v;
};

